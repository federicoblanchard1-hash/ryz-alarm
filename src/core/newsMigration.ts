/** Old and new topic ids in, current follows and entities out. Unknown ids are dropped. */
export function migrateNewsTopics(ids: string[]): { follows: string[]; entities: FollowedEntity[] } {
  const follows: string[] = [];
  const entities: FollowedEntity[] = [];
  for (const id of ids) {
    const to = nodeById(id) ? id : LEGACY[id];
    if (!to) continue;
    const m = to.match(/^(country|league|keyword):(.+)$/);
    if (m) {
      if (!entities.some((e) => e.kind === m[1] && e.name === m[2])) entities.push({ kind: m[1] as EntityKind, name: m[2] });
    } else if (nodeById(to) && !follows.includes(to)) follows.push(to);
  }
  return { follows, entities };
}

/** Does this list have ids from before the taxonomy? */
export function hasLegacyTopics(ids: string[]): boolean {
  return ids.some((id) => !nodeById(id));
}

/** News settings brought up to date: old topic ids moved over, missing preferences filled in. */
export function upgradeNewsSettings<T extends { newsTopics: string[] | null; news?: Partial<NewsPrefs> }>(s: T, locale?: string): T & { news: NewsPrefs } {
  const news = withNewsDefaults(s.news, locale);
  if (!s.newsTopics) return { ...s, news };
  const { follows, entities } = migrateNewsTopics(s.newsTopics);
  const known = new Set(news.entities.map((e) => `${e.kind}:${e.name}`));
  return { ...s, newsTopics: follows, news: { ...news, muted: news.muted.filter((id) => nodeById(id)), entities: [...news.entities, ...entities.filter((e) => !known.has(`${e.kind}:${e.name}`))] } };
}
