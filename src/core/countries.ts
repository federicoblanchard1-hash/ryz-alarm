/** A to Z, sorted so accented names like São Tomé fall in place. */
export const COUNTRIES: Country[] = [...LIST].sort((a, b) => a.name.localeCompare(b.name));

const BY_CODE = new Map(COUNTRIES.map((c) => [c.code, c]));

export function countryByCode(code: string | null | undefined): Country | undefined {
  return code ? BY_CODE.get(code.toUpperCase()) : undefined;
}

export function countryByName(name: string): Country | undefined {
  const n = name.trim().toLowerCase();
  return COUNTRIES.find((c) => c.name.toLowerCase() === n || c.also.some((a) => a.toLowerCase() === n));
}

/** The region of a country code; international sources have none. */
export function regionOf(code: string | null | undefined): RegionId | undefined {
  return countryByCode(code)?.region;
}
