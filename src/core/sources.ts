export const DEFAULT_EDITION = 'en-US';

/** Google News RSS for a search, in one edition. */
export function gnews(query: string, edition: string = DEFAULT_EDITION): string {
  const e = EDITIONS.find((x) => x.id === edition) ?? EDITIONS[0];
  return `https://news.google.com/rss/search?q=${encodeURIComponent(query)}&${e.params}`;
}

/** Google News top stories for an edition. */
export function gnewsTop(edition: string = DEFAULT_EDITION): string {
  const e = EDITIONS.find((x) => x.id === edition) ?? EDITIONS[0];
  return `https://news.google.com/rss?${e.params}`;
}

export type NewsSection = 'WORLD' | 'NATION' | 'BUSINESS' | 'TECHNOLOGY' | 'ENTERTAINMENT' | 'SPORTS' | 'SCIENCE' | 'HEALTH';

/** A Google News section (World, Business, Sports…) for an edition: the same section, in that edition's language. */
export function gnewsSection(section: NewsSection, edition: string = DEFAULT_EDITION): string {
  const e = EDITIONS.find((x) => x.id === edition) ?? EDITIONS[0];
  return `https://news.google.com/rss/headlines/section/topic/${section}?${e.params}`;
}

/** The edition a Google News URL was made for. */
export function editionOf(url: string): Edition | null {
  if (!url.includes('news.google.com')) return null;
  return EDITIONS.find((e) => url.includes(e.params)) ?? EDITIONS[0];
}

