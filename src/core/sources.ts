// The source registry: every publisher, agency, official body and channel Ryz
// reads, with its country, language, whether it's paywalled, and notes. Only
// legitimate channels: public RSS/Atom feeds and Google News RSS (which links
// to the original publishers). Each feed below was checked to return stories.
//
// The taxonomy (taxonomy.ts) points its topics at these feeds; a feed's source
// is found by matching its URL here, so a story can always say where it came
// from, in which language, and from which country.

export type SourceKind = 'news' | 'agency' | 'official' | 'specialist' | 'video' | 'podcast' | 'aggregator' | 'factcheck';

export interface Source {
  id: string;
  name: string;
  site: string;
  /** ISO 3166 country code, or 'INT' for international. */
  country: string;
  /** ISO 639-1 language code. */
  language: string;
  paywall: boolean;
  kind: SourceKind;
  /** Feed URLs start with one of these. */
  match: string[];
  notes?: string;
}

