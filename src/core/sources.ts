/** The registry entry a feed URL belongs to (Google News editions set language and country). */
export function sourceForFeed(url: string): Source | null {
  const s = SOURCES.find((x) => x.match.some((m) => url.startsWith(m))) ?? null;
  const ed = editionOf(url);
  if (s && ed) return { ...s, language: ed.language, country: ed.country };
  return s;
}

